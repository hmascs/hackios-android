#!/usr/bin/env bash
# Emit checked-in C arrays so the Android build does not require glslang.
set -euo pipefail
root=$(cd -- "$(dirname -- "$0")" && pwd)
work=$(realpath -- "$(mktemp -d)")
[[ "$work" == /* && "$work" != / && -O "$work" ]]
trap '[[ "$work" != / && -O "$work" ]] && rm -r -- "${work:?}"' EXIT
for stage in vert frag; do
    glslangValidator --quiet --target-env vulkan1.0 -Os -g0 -V "$root/triangle.$stage" -o "$work/$stage.spv"
    spirv-val --target-env vulkan1.0 "$work/$stage.spv"
done
python3 - "$work" <<'PY'
from pathlib import Path
import struct
import sys

print('/* Generated by generate-vulkan-shaders.sh; do not edit. */')
for stage in ('vert', 'frag'):
    raw = (Path(sys.argv[1]) / f'{stage}.spv').read_bytes()
    words = [f'0x{word:08x}u' for word, in struct.iter_unpack('<I', raw)]
    print(f'static const uint32_t triangle_{stage}[] = {{')
    for i in range(0, len(words), 6):
        print('    ' + ', '.join(words[i:i+6]) + ',')
    print('};')
PY
